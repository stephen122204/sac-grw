def fig_construction():
    """A real paired state: the interleaved-sign configuration after 10 steps."""
    from studies.study_round21_applicability import config
    from coupled_gradient_particles import advance_pair

    N, K, SEED = 12, 10, 2
    x0, m0, ul = config("clustered", N)
    captured = {}

    def capture(k, xA, mA, vA, xB, mB, vB):
        if k == K - 1:
            captured.update(xA=xA, mA=mA, xB=xB, mB=mB)

    advance_pair(
        (x0, m0, ul),
        0.1,
        0.005,
        K,
        np.random.default_rng(SEED),
        "FULL",
        lambda u: u,
        pre_diffusion=capture,
    )
    xA, mA, xB, mB = (captured[k] for k in ("xA", "mA", "xB", "mB"))
    assert np.all(np.diff(xA) >= 0) and np.all(np.diff(xB) >= 0)
    sA, sB = np.sign(mA), np.sign(mB)

    fig, axes = plt.subplots(1, 2, figsize=(6.6, 2.35))
    for ax, rule in zip(axes, ("rank", "within")):
        for y, xx, ss in ((1.0, xA, sA), (0.0, xB, sB)):
            for xi, si in zip(xx, ss):
                ax.plot(
                    [xi],
                    [y],
                    marker="o" if si > 0 else "s",
                    ms=5.4,
                    mfc="#e8e8e8" if si > 0 else "#333333",
                    mec="#111111",
                    mew=0.6,
                    linestyle="none",
                    zorder=3,
                )
        if rule == "rank":
            pairs = [(i, i, sA[i] * sB[i]) for i in range(len(xA))]
            ttl = "rank matching, multiplier $-\\,\\mathrm{sgn}(m_{A,i})\\mathrm{sgn}(m_{B,i})$"
        else:
            pairs = []
            for sgn in (1.0, -1.0):
                ia = np.flatnonzero(sA == sgn)
                ib = np.flatnonzero(sB == sgn)
                q = min(len(ia), len(ib))
                pairs += [(ia[k], ib[k], 1.0) for k in range(q)]
            ttl = "within-sign matching, multiplier $-1$"
        nsw = 0
        for i, j, mult in pairs:
            sync = mult < 0
            nsw += sync
            ax.plot(
                [xA[i], xB[j]],
                [1.0, 0.0],
                color="#c1272d" if sync else "#4d4d4d",
                ls=(0, (2.4, 1.4)) if sync else "-",
                lw=1.0,
                zorder=2,
                alpha=0.95,
            )
        ax.set_title(ttl, pad=5, fontsize=8.5)
        ax.set_ylim(-0.55, 1.55)
        ax.set_yticks([0.0, 1.0])
        ax.set_yticklabels(["replica $B$", "replica $A$"])
        ax.set_xlabel("position $x$")
        ax.set_xlim(min(xA.min(), xB.min()) - 0.04, max(xA.max(), xB.max()) + 0.04)
        ax.grid(axis="x", alpha=0.2)
        ax.grid(axis="y", alpha=0)
        ax.set_axisbelow(True)
        ax.text(
            0.985,
            0.06,
            f"{nsw} of {len(pairs)} synchronised",
            transform=ax.transAxes,
            ha="right",
            va="bottom",
            fontsize=7.5,
            color="#666666",
        )
    h = [
        Line2D(
            [],
            [],
            marker="o",
            ls="none",
            mfc="#e8e8e8",
            mec="#111",
            ms=5.4,
            label="$m_i>0$",
        ),
        Line2D(
            [],
            [],
            marker="s",
            ls="none",
            mfc="#333333",
            mec="#111",
            ms=5.4,
            label="$m_i<0$",
        ),
        Line2D([], [], color="#4d4d4d", lw=1.0, label="reflected: $Z_B=-Z_A$"),
        Line2D(
            [],
            [],
            color="#c1272d",
            lw=1.0,
            ls=(0, (2.4, 1.4)),
            label="synchronised: $Z_B=+Z_A$",
        ),
    ]
    fig.legend(
        handles=h,
        ncol=4,
        loc="lower center",
        bbox_to_anchor=(0.5, -0.10),
        frameon=False,
        columnspacing=1.5,
        handletextpad=0.6,
    )
    fig.tight_layout()
    fig.savefig(FIG / "fig1_construction.pdf")
    plt.close(fig)
    np.savez(
        HERE / "fig1_state.npz",
        xA=xA,
        mA=mA,
        xB=xB,
        mB=mB,
        config=np.array(["clustered"]),
        N=N,
        K=K,
        seed=SEED,
    )
    print("fig1_construction.pdf")


