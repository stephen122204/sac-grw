def fig_bias():  # Figure 5 in the manuscript
    jc = jload(ARCH / "round07_joint_cell_2026_09_09/joint_cell.json")["rows"]
    fig, ax = plt.subplots(figsize=(3.5, 2.6))
    styles = ["-", "--", ":"]
    for row, ls in zip(jc, styles):
        b2, Vf, Vr = row["b2_full"], row["V_full"], row["V_raw"]
        Cf, Cr = row["cost_full"], row["cost_raw"]
        W = np.geomspace(max(Cf, Cr), 4000 * Cf, 500)
        ratio = (b2 + Vf * Cf / W) / (b2 + Vr * Cr / W)
        ax.plot(
            W,
            ratio,
            ls=ls,
            color="#c1272d",
            lw=1.2,
            label=rf"$N={row['N']}$, $h={row['h']}$",
        )
        Bs = row["Bstar_full"]
        ax.plot(
            [Bs * Cf],
            [(b2 + Vf / Bs) / (b2 + Vr * Cr / (Bs * Cf))],
            marker="o",
            ms=4.5,
            mfc="white",
            mec="#c1272d",
            mew=1.1,
            zorder=4,
        )
    ax.set_xscale("log")
    ax.set_xlabel("common work budget (s)")
    ax.set_ylabel("mean squared error ratio")
    ax.set_title("sign-switched / reflected at fixed $N,h$", fontsize=8.5)
    ax.axhline(1.0, color="#111111", lw=0.7, ls=":")
    ax.set_ylim(0, 1.08)
    ax.legend(frameon=False, loc="lower right", fontsize=7.5)
    ax.text(
        0.03,
        0.06,
        r"$\circ$  $W=C_{\rm switch}V_{\rm switch}/b^{2}$",
        transform=ax.transAxes,
        fontsize=7.5,
        color="#666666",
        va="bottom",
    )
    fig.tight_layout()
    fig.savefig(FIG / "fig5_bias.pdf")
    plt.close(fig)
    print("fig5_bias.pdf")


