def fig_heldout():  # Figure 4 in the manuscript
    A = jload(HERE / "numbers.json")["heldout_A"]
    B = jload(HERE / "numbers.json")["heldout_B"]
    fig, axes = plt.subplots(1, 2, figsize=(6.6, 2.5))

    ax = axes[0]
    order = ["SINGLE", "RQMC", "RAW", "FULL"]
    w = [A["arms"][a]["work_s"] for a in order]
    ax.barh(range(len(order)), w, color=[C[a] for a in order], height=0.6)
    for i, a in enumerate(order):
        ax.text(
            w[i] + 0.12,
            i,
            f"{w[i]:.2f} s  ({A['arms'][a]['trajectories']} traj.)",
            va="center",
            fontsize=7.5,
        )
    ax.set_yticks(range(len(order)))
    ax.set_yticklabels([NAME[a] for a in order])
    ax.set_xlim(0, 9.2)
    ax.set_xlabel("measured work (s)")
    ax.set_title(r"experiment A: target $7\times10^{-6}$, $N=8192$", fontsize=8.5)
