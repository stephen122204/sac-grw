def fig_profiles():
    mech = jload(ARCH / "round23_mechanism_2026_09_10/mechanism.json")["rows"]
    sep = jload(ARCH / "round24_separation_2026_09_10/separation.json")["rows"]
    profiles = ["P1 single bump", "P2 two-pulse", "P3 oscillatory"]
    lab = {
        "P1 single bump": "single bump (2 sign regions)",
        "P2 two-pulse": "two-pulse (3)",
        "P3 oscillatory": "oscillatory (13)",
    }
    col = {
        "P1 single bump": "#4d4d4d",
        "P2 two-pulse": "#1f77b4",
        "P3 oscillatory": "#c1272d",
    }
    mk = {"P1 single bump": "o", "P2 two-pulse": "s", "P3 oscillatory": "^"}
    T = [0.25, 1.0, 2.0]
    fig, axes = plt.subplots(1, 2, figsize=(6.6, 2.7), sharex=True)

    ax = axes[0]
    for p in profiles:
        rs = [r for r in mech if r["profile"] == p]
        y = [r["full_over_within"] for r in rs]
        lo = [r["full_over_within"] - r["ci"][0] for r in rs]
        hi = [r["ci"][1] - r["full_over_within"] for r in rs]
        ax.errorbar(
            T,
            y,
            yerr=[lo, hi],
            color=col[p],
            marker=mk[p],
            ms=4.2,
            lw=1.1,
            capsize=2.5,
            label=lab[p],
        )
    ax.axhline(1.0, color="#111111", lw=0.7, ls=":")
    ax.set_xlabel("observation time $T$")
    ax.set_ylabel("variance ratio")
    ax.set_title("integrated variance ratio", fontsize=8.5)
    ax.set_xticks(T)
    ax.set_ylim(0.5, 1.08)

    ax = axes[1]
    for p in profiles:
        rs = [r for r in sep if r["kind"] == "matched_state" and r["profile"] == p]
        y = [r["ratio"] for r in rs]
        e = [2 * r["se"] for r in rs]
        ax.errorbar(
            T, y, yerr=e, color=col[p], marker=mk[p], ms=4.2, lw=1.1, capsize=2.5
        )
    ax.axhline(1.0, color="#111111", lw=0.7, ls=":")
    ax.set_xlabel("observation time $T$")
    ax.set_ylabel("matched-separation ratio")
    ax.set_title("matched-pair separation ratio", fontsize=8.5)
    ax.set_xticks(T)
    ax.set_ylim(0.5, 1.08)
    ax.text(
        0.98,
        0.05,
        r"$\leq 1$ by construction",
        transform=ax.transAxes,
        ha="right",
        va="bottom",
        fontsize=7.5,
        color="#666666",
    )
    h = [
        Line2D([], [], color=col[p], marker=mk[p], ms=4.2, lw=1.1, label=lab[p])
        for p in profiles
    ]
    fig.tight_layout()
    fig.legend(
        handles=h,
        ncol=3,
        loc="lower center",
        bbox_to_anchor=(0.5, -0.10),
        frameon=False,
        columnspacing=1.8,
    )
    fig.savefig(FIG / "fig3_profiles.pdf")
    plt.close(fig)
    print("fig3_profiles.pdf")


