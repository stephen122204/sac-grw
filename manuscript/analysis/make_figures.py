def fig_fields():
    z = np.load(REVIEW / "replayed_fields.npz")
    x = z["x"]
    ref = z["reference"]
    fig, axes = plt.subplots(
        1, 3, figsize=(6.8, 2.25), gridspec_kw={"width_ratios": [1, 1, 1.22]}
    )
    r = 3
    lim = 0
    for a in ("RAW", "FULL"):
        lim = max(
            lim, np.abs(z[f"{a}_A"][r] - ref).max(), np.abs(z[f"{a}_B"][r] - ref).max()
        )
    lim *= 1.08
    for ax, a in zip(axes[:2], ("RAW", "FULL")):
        ax.axhline(0.0, color="#111111", lw=0.6, ls=":")
        ax.plot(x, z[f"{a}_A"][r] - ref, color=C[a], lw=0.7, alpha=0.42)
        ax.plot(x, z[f"{a}_B"][r] - ref, color=C[a], lw=0.7, alpha=0.42)
        ax.plot(x, 0.5 * (z[f"{a}_A"][r] + z[f"{a}_B"][r]) - ref, color=C[a], lw=1.3)
        ax.set_xlim(-3, 3)
        ax.set_ylim(-lim, lim)
        ax.set_xlabel("$x$")
        ax.set_title(f"{NAME[a]} pairing", fontsize=8.5)
    axes[0].set_ylabel("$u(x,T)-u_{\\mathrm{ref}}(x,T)$")
    axes[1].set_yticklabels([])
    axes[0].text(
        0.03,
        0.04,
        "faint: the two replicas\nbold: their mean",
        transform=axes[0].transAxes,
        fontsize=7.2,
        color="#666666",
        va="bottom",
    )

    ax = axes[2]
    v = {a: 0.5 * (z[f"{a}_A"] + z[f"{a}_B"]) for a in ("RAW", "WITHIN", "FULL")}
    var = {a: v[a].var(0, ddof=1) for a in v}
    g = np.abs(np.gradient(ref, x[1] - x[0]))
    ax2 = ax.twinx()
    ax2.fill_between(x, 0, g / g.max(), color="#9ecae1", alpha=0.45, lw=0, zorder=0)
    ax2.set_ylim(0, 2.6)
    ax2.set_yticks([])
    ax2.grid(False)

    def smooth(y, w=13):
        k = np.ones(w) / w
        return np.convolve(np.pad(y, w // 2, mode="edge"), k, mode="valid")[: len(y)]

    for num, den, col, lab in (
        ("FULL", "RAW", C["FULL"], "vs reflected"),
        ("FULL", "WITHIN", C["WITHIN"], "vs within-sign"),
    ):
        rr = np.divide(
            var[num],
            var[den],
            out=np.full_like(var[num], np.nan),
            where=var[den] > 1e-10 * var[den].max(),
        )
        ax.plot(x, rr, color=col, lw=0.5, alpha=0.3, zorder=2)
        ax.plot(x, smooth(rr), color=col, lw=1.4, zorder=3, label=lab)
    ax.axhline(1.0, color="#111111", lw=0.6, ls=":")
    ax.set_xlim(-3, 3)
    ax.set_ylim(0, 1.45)
    ax.set_zorder(ax2.get_zorder() + 1)
    ax.patch.set_visible(False)
    ax.set_xlabel("$x$")
    ax.set_ylabel("pointwise variance ratio")
    ax.set_title("where the reduction sits", fontsize=8.5)
    ax.legend(frameon=False, loc="lower left", fontsize=7.2)
    fig.tight_layout()
    fig.savefig(FIG / "fig2_fields.pdf")
    plt.close(fig)
    print("fig2_fields.pdf")


